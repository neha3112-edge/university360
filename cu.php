                if ($carousel.length && !$carousel.hasClass('owl-loaded')) {
                    $carousel.owlCarousel({
                        loop: true,
                        autoplay: true,
                        margin: 20,
                        autoplayTimeout: 3500,
                        autoplayHoverPause: true,
                        dots: false,
                        nav: true,
                        navText: ['<i class="fa fa-angle-left"></i>', '<i class="fa fa-angle-right"></i>'],
                        responsive: {
                            0: { items: 1, nav: true },
                            768: { items: 2, nav: true },
