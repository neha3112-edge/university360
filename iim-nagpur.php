        // Inject IIM Nagpur tracking values into all forms
        function setIIMNagpurTrackingValues() {
            document.querySelectorAll('input[name="sub_source"]').forEach(function (el) {
                el.value = 'IIM Nagpur_Organic';
            });
            document.querySelectorAll('input[name="utm_medium"]').forEach(function (el) {
                if (!el.value) el.value = 'IIM Nagpur_Organic';
            });
            document.querySelectorAll('input[name="page_url"]').forEach(function (el) {
                el.value = window.location.href;
            });
        }

        document.addEventListener('DOMContentLoaded', function () {
            setIIMNagpurTrackingValues();

            var _origOpenPopup = window.openPopup;
            window.openPopup = function () {
                if (_origOpenPopup) _origOpenPopup.apply(this, arguments);
                setTimeout(setIIMNagpurTrackingValues, 10);
            };
        });

        function initIIMNagpurCarousel() {
            if (window.jQuery && jQuery.fn && jQuery.fn.owlCarousel) {
                var $carousel = jQuery(".amity-program-carousel");
                if ($carousel.length && !$carousel.hasClass('owl-loaded')) {
                    $carousel.owlCarousel({
                        loop: true,
                        autoplay: true,
                        margin: 20,
                        autoplayTimeout: 3500,
                        autoplayHoverPause: true,
                        dots: false,
                        nav: true,
                        navText: ['<i class="fa fa-angle-left"></i>', '<i class="fa fa-angle-right"></i>'],
                        responsive: {
                            0: { items: 1, nav: true },
                            768: { items: 2, nav: true },
                            1024: { items: 3, nav: true }
                        }
                    });
                }
            } else {
                setTimeout(initIIMNagpurCarousel, 50);
            }
        }

        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', initIIMNagpurCarousel);
        } else {
            initIIMNagpurCarousel();
